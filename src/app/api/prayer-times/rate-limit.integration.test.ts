import assert from "node:assert/strict";
import { createServer } from "node:http";
import type { AddressInfo } from "node:net";
import test from "node:test";
import { NextRequest } from "next/server";
import { GET } from "./route";
import { withConvexEnv } from "@/lib/testing/fake-convex";

// Integration controls only the external Convex HTTP boundary. A deployed E2E
// cannot hold one mutation or observe its cancellation without changing production.
test("a stalled limiter does not queue other API callers and its connection is aborted", async () => {
  let mutations = 0;
  let firstClosed = false;
  let firstFinished = false;
  let signalFirst: () => void = () => {};
  const firstArrived = new Promise<void>((resolve) => { signalFirst = resolve; });
  const server = createServer((req, res) => {
    let body = "";
    req.on("data", (chunk) => { body += chunk; });
    req.on("end", () => {
      // SAFETY: This listener receives only Convex SDK requests generated by this integration case.
      const message = JSON.parse(body) as { path: string };
      if (message.path === "rateLimits:consume" && ++mutations === 1) {
        res.on("close", () => { firstClosed = true; });
        signalFirst();
        return;
      }
      res.setHeader("Content-Type", "application/json");
      const value = message.path === "rateLimits:consume"
        ? { allowed: true, remaining: 59, resetAt: Date.now() + 60_000 }
        : null;
      res.end(JSON.stringify({ status: "success", value, logLines: [] }));
    });
  });
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  // SAFETY: The awaited TCP listener has an AddressInfo, not a Unix socket path.
  const { port } = server.address() as AddressInfo;
  const request = () => GET(new NextRequest(
    "http://localhost/api/prayer-times?mosque=madina-masjid-sheffield&date=2026-04-10",
    { headers: { "x-forwarded-for": `rate-integration-${crypto.randomUUID()}` } },
  ));
  try {
    await withConvexEnv({ CONVEX_URL: `http://127.0.0.1:${port}`, CONVEX_READ_SECRET: "integration-only" }, async () => {
      const first = request().finally(() => { firstFinished = true; });
      try {
        await firstArrived;
        const second = await request();
        const body = await second.text();
        const observed = {
          status: second.status,
          contentType: second.headers.get("content-type"),
          body: body.slice(0, 200),
          mutations,
          firstFinished,
        };
        assert.equal(second.status, 404, JSON.stringify(observed));
        assert.equal(mutations, 2, JSON.stringify(observed));
        assert.equal(firstFinished, false, JSON.stringify(observed));
      } finally {
        await first;
      }
      await new Promise<void>((resolve) => setImmediate(resolve));
      assert.equal(firstClosed, true, "the timed-out Convex request must close, not remain pending");
    });
  } finally {
    server.closeAllConnections();
    await new Promise<void>((resolve, reject) => server.close((error) => error ? reject(error) : resolve()));
  }
});
