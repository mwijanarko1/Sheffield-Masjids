def am(t: str) -> str:
    h, m = t.split(":")
    return f"{int(h):02d}:{m}"


def pm(t: str) -> str:
    h, m = t.split(":")
    hh = int(h)
    if 1 <= hh <= 11:
        hh += 12
    return f"{hh:02d}:{m}"


def month_json(name: str, rows: list[tuple], jummah: str = "13:30") -> dict:
    """rows: (date, fajr, fajr_iq, sunrise, dhuhr, dhuhr_iq, asr, asr_iq, maghrib, maghrib_iq, isha, isha_iq)"""
    prayer_times = []
    iqamah_times = []
    for r in rows:
        d, f, fi, su, dh, dhi, a, ai, mg, mgi, is_, isi = r
        prayer_times.append(
            {
                "date": d,
                "fajr": am(f),
                "shurooq": am(su),
                "dhuhr": pm(dh),
                "asr": pm(a),
                "maghrib": pm(mg),
                "isha": pm(is_),
            }
        )
        iqamah_times.append(
            {
                "date_range": str(d),
                "fajr": am(fi),
                "dhuhr": pm(dhi),
                "asr": pm(ai),
                "maghrib": pm(mgi),
                "isha": pm(isi),
            }
        )
    return {
        "month": name,
        "prayer_times": prayer_times,
        "iqamah_times": iqamah_times,
        "jummah_iqamah": jummah,
    }


